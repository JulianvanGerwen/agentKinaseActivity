#!/usr/bin/env python
"""Write results/ground_truth/GT_REPORT.md from the built GT/split files (aggregate counts only; reads the sealed
TEST tables for counts, never prints TEST labels). Run after build_gt.py, make_split.py, make_dev_cache.py."""
import json

import numpy as np
import pandas as pd

from gtlib import GT, SEALED

BINS = [-1, 0, 4, 19, 10 ** 9]
BL = ["0", "1-4", "5-19", ">=20"]


def md(df, index=True):
    df = df.copy()
    if index:
        df = df.reset_index()
    cols = [str(c) for c in df.columns]
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(out)


def main():
    gc = pd.concat([pd.read_csv(GT / "gt_conditions.tsv", sep="\t", dtype={"PMID": str}, keep_default_na=False),
                    pd.read_csv(SEALED / "gt_conditions.tsv", sep="\t", dtype={"PMID": str}, keep_default_na=False)], ignore_index=True)
    gp = pd.concat([pd.read_csv(GT / "gt_pairs.tsv", sep="\t", keep_default_na=False),
                    pd.read_csv(SEALED / "gt_pairs.tsv", sep="\t", keep_default_na=False)], ignore_index=True)
    hb = pd.concat([pd.read_csv(GT / "harmony_bins_group.tsv", sep="\t"),
                    pd.read_csv(SEALED / "harmony_bins_group.tsv", sep="\t")], ignore_index=True)
    cg = pd.concat([pd.read_csv(GT / "condition_groups.tsv", sep="\t", dtype=str, keep_default_na=False),
                    pd.read_csv(SEALED / "condition_groups.tsv", sep="\t", dtype=str, keep_default_na=False)], ignore_index=True)
    full = pd.read_csv(SEALED / "full" / "gt_conditions_full.tsv", sep="\t", dtype={"PMID": str}, keep_default_na=False)
    uni = pd.read_csv(GT / "kinase_universe.tsv", sep="\t", keep_default_na=False)
    qc = pd.read_csv(GT / "condition_qc.tsv", sep="\t", keep_default_na=False)
    doses = pd.read_csv(GT / "condition_doses.tsv", sep="\t", dtype=str)
    slog = json.loads((GT / "split_log.json").read_text())
    blog = json.loads((GT / "build_gt_log.json").read_text())
    cand = pd.read_csv(GT / "split_candidates.tsv", sep="\t")

    gp = gp.merge(gc[["conditionID", "source", "split", "role", "in_M1sel", "group_id"]], on="conditionID")
    gp["split2"] = np.where(gp["split"] == "test", "test", np.where(gp["split"] == "devconfirm", "devconfirm", "dev_cv"))
    gc["split2"] = np.where(gc["split"] == "test", "test", np.where(gc["split"] == "devconfirm", "devconfirm", "dev_cv"))
    pos = gp[gp["cls"].isin(["direct", "downstream"]) & (gp["role"] == "gt")]
    m1 = gp[(gp["cls"] == "direct") & gp["confidence"].isin(["high", "medium"]) & gp["in_M1sel"]]
    m1 = m1.merge(hb[["kinase", "group_id", "bin"]], on=["kinase", "group_id"], how="left")
    fam = dict(zip(uni["kinase"], [f if f else k for k, f in zip(uni["kinase"], uni["manning_family"])]))
    L = []
    w = L.append
    w("# Ground truth and split report (G1 candidate)\n")
    w("Generated by `scripts/gt_report.py` from `scripts/build_gt.py` + `scripts/make_split.py` outputs. "
      "Rule files: `results/ground_truth/*.tsv` (each with a note column). TEST rows are sealed in `cache/sealed/`; "
      "`results/ground_truth/gt_*.tsv` hold DEV (fold0-4) + devconfirm rows only.\n")
    w("## 1. Conditions by source and role\n")
    w(md(pd.crosstab(gc["source"], gc["role"], margins=True)))
    w("\nSources: H = Hijazi 2020 (31959955), D = decryptM (36926954), O = other studies (incl. Wilkes 26060313). "
      "Roles: gt (>=1 direct or downstream positive), null (decryptM Condition == Control), specificity "
      "(inhibitor/negative-control conditions with no positive: lipid-kinase-only drugs, Edelfosine/U73122, sub-potency "
      "decryptM doses, paradoxical-RAF-only conditions, R140/R212/R231), excluded (QC scale error / duplicate vector, "
      "or stimulus conditions whose labels all fall outside the <=4 h window).\n")
    w("## 2. Pairs by source, class and confidence (gt conditions)\n")
    t = gp[gp["role"] == "gt"].assign(cc=lambda d: d["cls"] + ":" + d["confidence"].replace("", "-"))
    w(md(pd.crosstab(t["source"], t["cc"], margins=True)))
    w("\nSigns of direct positives: " + str(gp[(gp.cls == "direct") & (gp.role == "gt")]["sign"].value_counts().to_dict())
      + ". Masked rules (first token): " + str(gp[gp.cls == "masked"]["rule_id"].str.split(";").str[0]
                                               .str.replace(r"_.*", "", regex=True).value_counts().head(10).to_dict()) + "\n")
    w("## 3. Split\n")
    w(f"Chosen candidate seed **{slog['chosen_seed']}** of 100 (pre-registered distance d = {slog['chosen_distance']:.4f}; "
      f"{slog['n_feasible_candidates']} of 100 candidates had >= 20 % TEST kinases unseen in DEV; candidate distances "
      f"min/median/max = {cand.distance.min():.3f}/{cand.distance.median():.3f}/{cand.distance.max():.3f}). "
      f"{slog['n_groups']} union-find groups ({slog['n_gt_groups']} contain GT conditions).\n")
    lg = slog["largest_group"]
    gsz = cg.groupby("group_id").size()
    gt_groups = set(gc["group_id"])
    lgt = gsz[gsz.index.isin(gt_groups)].sort_values(ascending=False)
    lgt_id = lgt.index[0]
    w(f"Largest group: {lg['group_id']} with {lg['n_conditions']} conditions (PMIDs {lg['pmids']}; split {lg['split']}; "
      f"decryptM rituximab, no GT). Largest group holding GT: {lgt_id} with {lgt.iloc[0]} conditions over "
      f"{cg[cg.group_id == lgt_id].PMID.nunique()} studies, split {gc[gc.group_id == lgt_id].split.iloc[0]} "
      f"(drugs: {', '.join(cg[cg.group_id == lgt_id].drugs.str.split(';').explode().value_counts().head(8).index)}).\n")
    w(md(pd.DataFrame({"all conditions": cg["split"].value_counts().sort_index(),
                       "GT conditions": gc["split"].value_counts().sort_index(),
                       "gt-role conditions": gc[gc.role == "gt"]["split"].value_counts().sort_index(),
                       "M1-sel conditions": gc[gc.in_M1sel]["split"].value_counts().sort_index(),
                       "M1-sel pairs": m1["split"].value_counts().sort_index(),
                       "groups": cg.groupby("split")["group_id"].nunique()}).fillna(0).astype(int)))
    w("\n### Per source x split\n")
    w(md(pd.crosstab([gc[gc.role == "gt"]["source"]], gc[gc.role == "gt"]["split2"]).rename_axis("gt conditions")))
    w("")
    w(md(pd.crosstab(m1["source"], m1["split2"], margins=True).rename_axis("M1-sel pairs")))
    w("\n### TEST share of M1-sel pairs per source x harmony bin (split-selection cells)\n")
    tab = pd.crosstab([m1["source"], m1["bin"]], m1["split2"] == "test")
    tab.columns = ["dev+confirm", "test"]
    tab["test_share"] = (tab["test"] / tab.sum(axis=1)).round(3)
    w(md(tab))
    w("## 4. Kinases\n")
    dev_pos = set(pos[(pos.cls == "direct") & pos.confidence.isin(["high", "medium"]) & (pos.split != "test")].kinase)
    test_k = set(m1[m1.split == "test"].kinase)
    dev_fam = {fam.get(k, k) for k in dev_pos}
    rows = []
    for nm, d in [("all", m1), ("dev_cv", m1[m1.split2 == "dev_cv"]), ("devconfirm", m1[m1.split2 == "devconfirm"]),
                  ("test", m1[m1.split2 == "test"])]:
        r = {"set": nm, "M1-sel kinases": d.kinase.nunique()}
        for b in BL:
            r[f"bin {b}"] = d[d["bin"] == b].kinase.nunique()
        rows.append(r)
    w("M1-sel kinases (direct, high/medium, conditions with 1-10 direct targets). Harmony bin per (kinase, group) = "
      "median quantified PSP substrates over the group's conditions where the kinase is a positive; a kinase can "
      "appear in several bins.\n")
    w(md(pd.DataFrame(rows), index=False))
    allk = pos[(pos.cls == "direct") & pos.confidence.isin(["high", "medium"])]
    allk = allk.merge(hb[["kinase", "group_id", "bin"]], on=["kinase", "group_id"], how="left")
    w(f"\nM1-all (all direct high/medium positives in gt conditions): {allk.kinase.nunique()} kinases "
      f"({', '.join(f'bin {b}: {allk[allk.bin == b].kinase.nunique()}' for b in BL)}). Any direct positive (incl. low): "
      f"{pos[pos.cls == 'direct'].kinase.nunique()} kinases; downstream positives: {pos[pos.cls == 'downstream'].kinase.nunique()} kinases.\n")
    w(f"TEST M1-sel kinases: {len(test_k)}; **T-unseen** (never a high/medium direct positive in any DEV/devconfirm gt "
      f"condition): {len(test_k - dev_pos)}; **T-family-unseen** (no DEV positive in the same Manning family): "
      f"{len({k for k in test_k if fam.get(k, k) not in dev_fam})}.\n")
    w("M1-sel kinases per source: " + str(m1.groupby("source").kinase.nunique().to_dict()) + "\n")
    w("## 5. Doses\n")
    w("Hijazi per-drug doses: NOT obtainable. The paper states 'cells were incubated with 1-10 uM of compound for 1 h'; "
      "Supplementary Dataset 1 (MOESM3, kinase-inhibitor selectivity: DiscoverX % control + Klaeger Kd) and Dataset 2 "
      "(phosphopeptides) and the SI PDF contain no per-drug concentrations; PRIDE PXD015943 lists only raw/mzid files. "
      "-> pre-registered default 10 uM for all Hijazi conditions (conservative: more off-target masking). "
      "decryptM doses parsed from the condition label (antibody ng/mL converted with 148 kDa); study notations in "
      "`condition_doses_manual.tsv`; other doses parsed from text; unparsed -> default 10 uM (flagged).\n")
    w(md(doses.drop_duplicates(["conditionID", "agent"])["dose_source"].value_counts().rename("condition-agent rows").to_frame()))
    w("\n## 6. Excluded GT conditions (QC + time window)\n")
    ex = gc[gc.role == "excluded"].merge(qc[["conditionID", "sd", "max_abs", "duplicate_of", "qc_status"]], on="conditionID")
    ex["reason"] = np.where(ex["qc_status"] == "ok", "stimulus labels all > 4 h (time window)", ex["qc_status"])
    w(md(ex[["conditionID", "source", "reason", "sd", "max_abs", "duplicate_of"]], index=False))
    w(f"\nAll compendium conditions: {qc.qc_status.value_counts().to_dict()} (scale error = SD > 3 or max |log2FC| > 20; "
      "duplicate = byte-identical vector, first conditionID kept). Non-GT flagged conditions stay in the DEV cache with "
      "their qc_status.\n")
    w("## 7. Minimum detectable effect\n")
    w("MDE placeholder: to be computed at G1 as multiplier x SE(Delta M1-sel) from a group bootstrap (B=2000, seed 0) of the "
      "reference pair z-score vs prior-only on the chosen TEST (B4; r3 C1 suggests multiplier 3.5 instead of 2.5). "
      "Requires the frozen harness and baseline scores; not computed here.\n")
    w("## 8. Implementation decisions (PI decisions 2026-10-27 applied)\n")
    w("""- Precedence per (condition, kinase): paradox-drop > direct > downstream > masked > negative. Curated downstream labels
  are not overwritten by pathway masks; downstream pairs are excluded from negatives.
- Stimuli: `stimulus_kinases.tsv` gives direct (receptor + near-certain first-tier, e.g. EGF -> EGFR, MAPK1/3; insulin ->
  INSR, AKT1/2; TNF -> MAP3K7, IKBKB; DSB -> ATM, CHEK2; replication stress -> ATR, CHEK1; UV -> ATR, MAPK14, MAPK8) and
  downstream kinases. Stimulus labels only for treatment <= 4 h (later -> masked, rule TIME_GT4H). Time from the
  Condition text, else the Timepoint field; unknown time kept and noted.
- decryptM: each dose is its own condition; n_targets per dose after the dose rule (target positive iff dose >= Kd_app
  for ATP-competitive drugs with a finite Kd_app, else dose >= literature potency for allosteric/covalent/PIKK/antibody or
  missing Kd; below -> target masked; condition with no positive -> specificity). Curated decryptM downstream rows
  are kept only if a drug target (or agent-level potency for lipid-kinase-only drugs) passes the rule.
- Off-target masks: Kd_app <= 3 x dose, profile per drug = highest-priority source that profiled it
  (Klaeger 2017 > Reinecke 2024 > Davis 2011), lower sources fill unmeasured kinases, Hijazi kinhib matrix last
  (Kd := 0). Klaeger protein groups expanded to all genes. kinoplex: the kinaseSubMain kinoplex files are a structural
  S/T/Y atlas and contain no drug-kinase affinities, so that tier is empty. Designated targets of the condition's
  rules are exempt from off-target masks.
- Paralog mask: a kinase whose PSP substrates (>= 1) are >= 80 % shared with a positive is masked
  (`paralog_pairs.tsv`).
- Paradoxical RAF: drugs with raf_type = paradox (vemurafenib, dabrafenib, SB590885, unnamed 'BRAFi', encorafenib,
  PLX4720) in lines whose BRAF status is not V600 (WT or unknown, `cell_line_genotypes.tsv`): BRAF/ARAF/RAF1 positives
  dropped (masked) and MAP2K1/2, MAPK1/3, RSKs masked. BRAF-V600 lines keep BRAF -1 and the curated MEK/ERK
  downstream -1.
- Lipid kinases, PRKY, Q6ZSR9 are outside U and dropped; BCR/ABL -> ABL1. Kinhib tokens dropped (rows):
  """ + json.dumps(blog["kinhib_tokens_dropped_not_in_U"]) + """
- r1/r2 fixes: LCK (TCR) and TGFBR2 (TGF-beta) medium; AKT in R177/R247 -> downstream (R209 insulin: AKT1/2 direct by
  the PI stimulus rule); PDPK1 symbol; R140/R212/R231 negative-control rows -> specificity only; CDK7i -> CDK1/2/9 and
  p38i -> MSK1/2 masks added; 19651622 SB202190 rows get MAPK14/11 (low).
- Roles beyond the contract: `excluded` (r3 S3) used for QC failures and time-window-only stimulus conditions.
- Sealing: TEST rows in cache/sealed/*.tsv (harness load_sealed_test naming); `test_condition_hashes.txt` holds salted sha256 of TEST conditionIDs
  (salt sealed). The pre-v1 draft outputs (candidate_gt*.tsv, hijazi_conditions.tsv, klaeger_hijazi_targets.tsv,
  gt_summary.json) contained TEST labels and were moved to cache/sealed/draft_candidate_v0/;
  scripts/build_candidate_gt.py and scripts/profile_data.py still refer to them (superseded).
- Hijazi direct positives are all confidence high (kinhib matrix; no tiering beyond M1-sel), as DESIGN §3 GT-H.
""")
    w("## 9. Decisions needing expert check\n")
    w("""1. Stimulus first-tier lists (`stimulus_kinases.tsv`): MAPK1/3 as *direct* for EGF/FGF/NGF; MAP2K1/2 kept downstream;
   CHEK2 direct for DSB and CHEK1 for replication stress; UV -> MAPK8/MAPK14 direct; IFN type unspecified (JAK1 medium,
   JAK2/TYK2 low); PMA -> PRKCA/B/D/E only.
2. RTK/TK-inhibitor pathway mask (class TK) masks the whole RAS-ERK and PI3K-AKT axis for every TK inhibitor (incl.
   Hijazi promiscuous TKIs) — conservative; it removes many negatives.
3. Literature off-target table (`offtarget_literature.tsv`) and potency table (`drug_potency_manual.tsv`) were written
   from memory of the cited papers (Bain 2007, Davies 2000, Liu 2012, ...); values/kinases need verification. Notably
   selumetinib MEK2 50 nM, MRT = MRT67307 assumption, trastuzumab/pertuzumab Kd 5 nM.
4. Default dose 10 uM for Hijazi and unparsed studies (459 conditions): with Kd <= 3 x dose this masks almost every
   kinobead binder of the drug.
5. Paradox rule: sorafenib typed 'typeII' (no paradox) and LY3009120 'panraf'; unnamed BRAFi (38047086 organoids,
   genotype unknown) treated as paradox-inducing -> those 6 conditions have no positives. HCT116 vemurafenib time
   course (28188228) becomes specificity controls.
6. Paralog rule uses the masked kinase's PSP set as denominator with no minimum size: kinases with 1-2 PSP substrates that
   are shared with a positive are masked.
7. Hijazi column AZD6432 is assumed to be AZD6482 (PI3Kbeta).
8. decryptM antibodies (trastuzumab/pertuzumab, low confidence) dose conversion and the SHP099 indirect downstream labels.
9. Combination decryptM labels "<a>to<b>" = molar ratio (first:second drug; Zecha 2023 Fig. 4E: selumetinib:MK-2206 3:1).
   Which drug the label dose refers to is not documented -> `combination_doses_manual.tsv` marks all combinations
   ambiguous: per-drug dose = max over readings (label = first / second / total) for masks, all labels capped low (audit 2026-10-27).
11. Cellular-potency override (`drug_cellular_potency.tsv`, audit 2026-10-27): for a drug's primary target, a documented
   cellular IC50 lower than Kd_app / potency-table value is used as the decryptM dose gate (gefitinib/EGFR, dasatinib/ABL1, ...).
10. Groups: unnamed class tokens (MEKi, p38i, ...) link conditions across studies; DNA-damaging/other non-kinase drugs
    (HU, NCS, paclitaxel, coumarin ...) also link studies. Stimulus ligands (EGF, TNF) do not link studies.
""")
    w("## 10. Build log\n")
    w("```\n" + json.dumps({k: blog[k] for k in ("n_gt_conditions_by_role", "n_pairs_by_cls", "dose_sources",
                                                "qc_status_all_conditions", "rules_without_match")}, indent=1) + "\n```\n")
    (GT / "GT_REPORT.md").write_text("\n".join(L) + "\n")
    print("wrote GT_REPORT.md")


if __name__ == "__main__":
    main()
